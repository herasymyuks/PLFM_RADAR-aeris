/* Signed VGA magnitude of a 6-bit I or Q word (-31..+31). */
static inline int adar1000_vm_signed(uint8_t word)
{
    int mag = (int)(word & ADAR1000_VM_GAIN_MASK);
    return (word & ADAR1000_VM_POL_BIT) ? mag : -mag;
}

