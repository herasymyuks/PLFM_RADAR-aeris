/*
 * adar1000_vm_tables.h - ADAR1000 vector-modulator phase tables (128 steps of 2.8125 deg).
 *
 * SOURCE: Analog Devices ADAR1000 data sheet Rev. B (7/2022), repository copy
 *   "7_Components Datasheets and Application notes/ADAR1000.pdf", pages 35-36,
 *   Table 10 (Quadrant 1, 0 .. 87.1875 deg), Table 11 (Quadrant 2, 90 .. 177.1875 deg),
 *   Table 12 (Quadrant 3, 180 .. 267.1875 deg), Table 13 (Quadrant 4, 270 .. 357.1875 deg):
 *   "Mapping of I and Q VM VGA Register Settings to Phase Setting".
 *   Extracted with `pdftotext -layout` and parsed mechanically (beta/stm32/tests/test_adar_vm_tables.c
 *   re-derives the angle of every row from the I/Q words and checks monotonicity and spot values).
 *
 * REGISTER BIT LAYOUT (Table 47/48, CHx_RX_PHASE_I/Q 0x014..0x01B; Table 59.. for CHx_TX_PHASE_I/Q 0x020..0x027):
 *   bit 7:6  reserved (0)
 *   bit 5    RX/TX_VM_CHx_POL_I (or _Q): vector polarity. 1 = positive, 0 = negative
 *            (Table 10 row 0 deg: I = 0x3F -> +31, Q = 0x20 -> +0; Table 12 row 180 deg: I = 0x1F -> -31;
 *             data sheet example "0x014 = 0x36: I input positive, magnitude 0x16").
 *   bit 4:0  RX/TX_VM_CHx_GAIN_I (or _Q): VGA magnitude 0..31
 *   phase = atan2(sign(Q)*|Q|, sign(I)*|I|)
 *
 * VM_GAIN: the data sheet gives no per-phase gain correction. Theory of Operation, "Phase and Gain Control"
 * (page 33): the Table 10-13 values "sweep the phase while keeping the gain of the vector modulator constant";
 * "if the values given in Table 10 .. Table 13 are used, the VGA exclusively executes the gain control"
 * (CHx_RX_GAIN 0x010-0x013: bit 7 attenuator bypass, bits 6:0 VGA gain). Therefore ADAR1000_VM_GAIN is all
 * zeros = "no per-step correction"; it is not applied by ADAR1000_Manager (kept for API compatibility).
 *
 * The C arrays in adar1000_vm_tables.c and the ADAR1000Manager::VM_* class members are generated from the
 * same macros below.
 */
