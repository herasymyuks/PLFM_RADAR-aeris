    p = os.path.join(ROOT, "engineering", "ELECTRICAL", "netlists", f"{board}_netlist.csv")
    out = {}
    if os.path.isfile(p):
        for r in csv.DictReader(open(p, newline="", encoding="utf-8")):
            if re.match(r"^X\d+$", r["part"]) and r["net"] not in ("GND",):
                out.setdefault(r["part"], set()).add(r["net"])
    return out
