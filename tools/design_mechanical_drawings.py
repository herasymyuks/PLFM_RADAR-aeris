def pa_xyz(n, ref):
    px, pz = L.pa_positions()[n - 1]
    if ref in pa:
        return (px + pa[ref][0], L.Y_PA, pz + pa[ref][1])
    return (px + 17, L.Y_PA, pz + 30)
def length(a, b, kind):
    if a is None or b is None:
        return None
    d = abs(a[0] - b[0]) + abs(a[1] - b[1]) + abs(a[2] - b[2])
    extra = 40 if kind.startswith("coax") else 60
    return int(math.ceil((d + extra) / 10.0) * 10)
